-- Baseline schema of the pre-Flyway application. Existing installations must
-- explicitly baseline at version 1 after backup and schema comparison.
CREATE TABLE users (
 user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(255) UNIQUE, email VARCHAR(255) UNIQUE, password VARCHAR(255),
 phone INTEGER UNIQUE NOT NULL, created_at DATE, role VARCHAR(255)
);
CREATE TABLE restaurant_tables (
 restaurant_table_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurant_table_number INTEGER NOT NULL, capacity INTEGER NOT NULL,
 table_qr_code_value VARCHAR(255), restaurant_table_status BOOLEAN NOT NULL
);
CREATE TABLE dining_sessions (
 dining_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 start_at TIMESTAMP(6), end_at TIMESTAMP(6), dining_status VARCHAR(255),
 restaurant_table_id BIGINT REFERENCES restaurant_tables
);
CREATE TABLE foods (
 food_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 food_name VARCHAR(255), is_available BOOLEAN NOT NULL, description VARCHAR(255),
 quantity INTEGER NOT NULL, food_image_url VARCHAR(255), price DOUBLE PRECISION NOT NULL
);
CREATE TABLE food_category (
 food_category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 food_category_name VARCHAR(255)
);
CREATE TABLE food_category_map (
 food_category_map_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 food_id BIGINT REFERENCES foods, food_category_id BIGINT REFERENCES food_category
);
CREATE TABLE menus (
 menu_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 menu_name VARCHAR(255), menu_desc VARCHAR(255), is_activated BOOLEAN NOT NULL
);
CREATE TABLE menu_items (
 menu_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 food_id BIGINT REFERENCES foods, menu_id BIGINT REFERENCES menus
);
CREATE TABLE orders (
 order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TIMESTAMP(6), order_price DOUBLE PRECISION NOT NULL,
 order_status VARCHAR(255), order_number VARCHAR(255) NOT NULL UNIQUE,
 dining_session_id BIGINT REFERENCES dining_sessions
);
CREATE TABLE order_items (
 order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 quantity INTEGER NOT NULL, total_price DOUBLE PRECISION NOT NULL,
 order_id BIGINT REFERENCES orders, food_id BIGINT REFERENCES foods
);
CREATE TABLE memberships (
 membership_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 membership_rank VARCHAR(255), min_spent DOUBLE PRECISION NOT NULL,
 discount_rate DOUBLE PRECISION NOT NULL
);
CREATE TABLE members (
 member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name VARCHAR(255), last_name VARCHAR(255), member_phone VARCHAR(255),
 member_email VARCHAR(255), member_rank VARCHAR(255), total_spent DOUBLE PRECISION NOT NULL
);
CREATE TABLE invoices (
 invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pay_before_discount DOUBLE PRECISION NOT NULL, discount_amount DOUBLE PRECISION NOT NULL,
 total_pay DOUBLE PRECISION NOT NULL, created_at TIMESTAMP(6), invoice_status VARCHAR(255),
 dining_session_id BIGINT REFERENCES dining_sessions, member_id BIGINT REFERENCES members
);
CREATE TABLE payments (
 payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 amount NUMERIC(38,2), paid_at TIMESTAMP(6), paypal_order_id VARCHAR(255),
 payment_status SMALLINT CHECK (payment_status BETWEEN 0 AND 1),
 cash_change NUMERIC(10,2) NOT NULL DEFAULT 0, payment_method VARCHAR(255),
 invoice_id BIGINT REFERENCES invoices
);
