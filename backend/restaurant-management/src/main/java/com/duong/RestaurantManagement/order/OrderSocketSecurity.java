package com.duong.RestaurantManagement.order;

import com.duong.RestaurantManagement.auth.service.JwtService;
import com.duong.RestaurantManagement.auth.service.MyUserDetailsService;
import com.duong.RestaurantManagement.user.model.User;
import io.jsonwebtoken.Claims;
import io.jsonwebtoken.JwtException;
import lombok.RequiredArgsConstructor;
import org.springframework.messaging.Message;
import org.springframework.messaging.MessageChannel;
import org.springframework.messaging.simp.stomp.StompCommand;
import org.springframework.messaging.simp.stomp.StompHeaderAccessor;
import org.springframework.messaging.support.ChannelInterceptor;
import org.springframework.messaging.support.MessageHeaderAccessor;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.authentication.AccountStatusUserDetailsChecker;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.AuthenticationException;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.stereotype.Component;

import java.util.Date;
import java.util.List;

@Component
@RequiredArgsConstructor
public class OrderSocketSecurity implements ChannelInterceptor {

    private final JwtService jwt;
    private final MyUserDetailsService users;

    @Override
    public Message<?> preSend(Message<?> message, MessageChannel channel) {

        StompHeaderAccessor headers = MessageHeaderAccessor.getAccessor(message, StompHeaderAccessor.class);

        if (headers == null) throw new AccessDeniedException("STOMP headers required");

        StompCommand command = headers.getCommand();

        if (command == StompCommand.CONNECT) {
            headers.setUser(authenticate(headers.getFirstNativeHeader("Authorization")));
            return message;
        }
        // Disconnect may also be generated by Spring during connection cleanup.
        if (command == StompCommand.DISCONNECT) return message;

        if (!(headers.getUser() instanceof Authentication auth) || !auth.isAuthenticated()
                || !(auth.getDetails() instanceof Date expires) || !expires.after(new Date())) {
            throw new AccessDeniedException("A valid connection token is required");
        }
        if (command == StompCommand.SUBSCRIBE) {
            String destination = headers.getDestination();
            boolean staff = auth.getAuthorities().stream().anyMatch(a ->
                    a.getAuthority().equals("ROLE_ADMIN") || a.getAuthority().equals("ROLE_MANAGER"));
            boolean customer = auth.getAuthorities().stream().anyMatch(a -> a.getAuthority().equals("ROLE_CUSTOMER"));
            if (staff && ("/topic/orders/".equals(destination) || "/topic/orders/status".equals(destination))) return message;

            if (customer && ("/topic/orders/session/" + auth.getName()).equals(destination)) return message;

            throw new AccessDeniedException("Order subscription is not allowed");
        }
        if (command == null || command == StompCommand.UNSUBSCRIBE) return message;
        throw new AccessDeniedException("Clients may only subscribe to order updates");
    }

    private Authentication authenticate(String header) {
        if (header == null || !header.startsWith("Bearer ")) throw new AccessDeniedException("Bearer token required");
        try {
            Claims claims = jwt.claims(header.substring(7));
            String subject = claims.getSubject();
            if (subject == null || subject.isBlank() || claims.getExpiration() == null) {
                throw new AccessDeniedException("Invalid connection token");
            }
            UsernamePasswordAuthenticationToken auth;
            if ("dining".equals(claims.get("purpose", String.class))) {
                if (!subject.matches("[1-9][0-9]*")) throw new AccessDeniedException("Invalid dining session");
                auth = new UsernamePasswordAuthenticationToken(subject, null, List.of(new SimpleGrantedAuthority("ROLE_CUSTOMER")));
            } else if ("access".equals(claims.get("purpose", String.class))) {
                UserDetails user = users.loadUserByUsername(subject);

                new AccountStatusUserDetailsChecker().check(user);

                if (user.getAuthorities().stream().noneMatch(a -> a.getAuthority().equals("ROLE_ADMIN")
                        || a.getAuthority().equals("ROLE_MANAGER"))) throw new AccessDeniedException("Staff access required");
                auth = new UsernamePasswordAuthenticationToken(user, null, user.getAuthorities());
            } else {
                throw new AccessDeniedException("Access or dining token required");
            }
            auth.setDetails(claims.getExpiration());
            return auth;

        } catch (JwtException | IllegalArgumentException | AuthenticationException ex) {
            throw new AccessDeniedException("Invalid or expired connection token", ex);
        }
    }
}
